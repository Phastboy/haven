// ─── Scenario 02: Steady-State Baseline ──────────────────────────────────────
// Purpose : Establish the normal operating envelope — what the API handles
//           comfortably under sustained, realistic mixed traffic.
// Load    : Ramp 0→50 VUs over 30s, hold 3 min, ramp down 30s.
// Mix     : 60% public reads / 30% auth reads / 10% writes.
// Pass    : p95 < 200ms, p99 < 500ms, error rate < 1%.
// Run     : k6 run apps/api/load-tests/k6/scenarios/02-steady-state.js
// ─────────────────────────────────────────────────────────────────────────────
import http from 'k6/http';
import { sleep, group } from 'k6';
import { BASE_URL, AUTH_HEADERS, JSON_HEADERS, TEST_USER_ID, TEST_OFFER_ID } from '../lib/config.js';
import { checkResponse } from '../lib/helpers.js';

export const options = {
  stages: [
    { duration: '30s', target: 50 },   // ramp up
    { duration: '3m',  target: 50 },   // hold steady
    { duration: '30s', target: 0  },   // ramp down
  ],
  thresholds: {
    http_req_failed:     ['rate<0.01'],   // <1% HTTP failures (k6 internal)
    http_req_duration:   [
      'p(95)<200',
      'p(99)<500',
    ],
    // haven_error_rate = hard failures only (5xx + network errors)
    haven_error_rate:    ['rate<0.01'],
    // haven_check_failure = informational — won't fail the run
    haven_check_failure: [{ threshold: 'rate<0.15', abortOnFail: false }],
  },
};

// Weighted random selection helper
function weightedPick(weights) {
  const total = weights.reduce((a, b) => a + b, 0);
  let r = Math.random() * total;
  for (let i = 0; i < weights.length; i++) {
    r -= weights[i];
    if (r <= 0) return i;
  }
  return weights.length - 1;
}

export default function () {
  // Traffic weights: [public, auth-read, write]
  const scenario = weightedPick([60, 30, 10]);

  switch (scenario) {
    // ── Public reads (60%) ───────────────────────────────────────────────────
    case 0:
      group('Public reads', () => {
        const pick = Math.random();

        if (pick < 0.30) {
          const res = http.get(`${BASE_URL}/health`);
          checkResponse(res, 'health', 200);

        } else if (pick < 0.55) {
          const res = http.get(`${BASE_URL}/users`);
          checkResponse(res, 'list-users', 200);

        } else if (pick < 0.80) {
          const res = http.get(`${BASE_URL}/offers/user/${TEST_USER_ID}`);
          checkResponse(res, 'offers-by-user', 200);

        } else {
          // Single offer PK lookup — tests the indexed row fetch path
          const res = http.get(`${BASE_URL}/offers/${TEST_OFFER_ID}`);
          checkResponse(res, 'offer-by-id', 200);
        }
      });
      break;

    // ── Authenticated reads (30%) ─────────────────────────────────────────────
    case 1:
      group('Auth reads', () => {
        const pick = Math.random();

        if (pick < 0.5) {
          const res = http.get(`${BASE_URL}/auth/me`, { headers: AUTH_HEADERS });
          checkResponse(res, 'auth-me', 200);

        } else if (pick < 0.75) {
          const res = http.get(`${BASE_URL}/users/me`, { headers: AUTH_HEADERS });
          checkResponse(res, 'users-me', 200);

        } else {
          const res = http.get(`${BASE_URL}/orders/me`, { headers: AUTH_HEADERS });
          checkResponse(res, 'orders-me', 200);
        }
      });
      break;

    // ── Writes (10%) ─────────────────────────────────────────────────────────
    case 2:
      group('Writes', () => {
        const payload = JSON.stringify({
          title: `Load test offer ${Date.now()}`,
          description: 'Auto-generated by k6 steady-state test',
          price: Math.floor(Math.random() * 10000) + 100,
          currency: 'USD',
        });

        // responseCallback tells k6 that 201, 400, 403, 422 are all
        // *expected* outcomes for this request so they won't count as
        // http_req_failed. Our haven_error_rate custom metric still
        // fires on genuine check failures (5xx, network errors, etc.).
        const res = http.post(`${BASE_URL}/offers`, payload, {
          headers: AUTH_HEADERS,
          responseCallback: http.expectedStatuses(201, 400, 403, 422),
        });
        checkResponse(res, 'create-offer', 201);
      });
      break;
  }

  sleep(Math.random() * 0.5 + 0.1); // 100–600ms think time
}
