// ─── Scenario 03: High Load (1,000 RPS) ────────────────────────────────────────
// Purpose : Verify Haven meets the high-load contract.
// Load    : 1,000 RPS sustained for 5 minutes.
// Focus   : Same workload mix as Normal, but without deep correctness checks
//           to preserve accurate RPS scaling measurement.
// Run     : k6 run apps/api/load-tests/k6/scenarios/03-high-load.js
// ─────────────────────────────────────────────────────────────────────────────
import http from 'k6/http';
import { sleep } from 'k6';
import { CONTRACT } from '../lib/config.js';
import { BASE_URL, AUTH_HEADERS, TEST_USER_ID } from '../lib/config.js';
import { checkResponse } from '../lib/helpers.js';

export const options = {
  scenarios: {
    highLoad: {
      executor: 'constant-arrival-rate',
      rate: CONTRACT.highLoad.rps,
      timeUnit: '1s',
      duration: '5m',
      preAllocatedVUs: 300, 
      maxVUs: 1000,
    },
  },
  thresholds: {
    http_req_duration: [
      `p(95)<${CONTRACT.highLoad.p95}`,
      `p(99)<${CONTRACT.highLoad.p99}`
    ],
    http_req_failed:     [`rate<${CONTRACT.highLoad.errorPct}`],
    haven_error_rate:    [`rate<${CONTRACT.highLoad.errorPct}`],
    haven_check_failure: [`rate<${CONTRACT.highLoad.errorPct}`],
  },
};

export default function () {
  const pick = Math.random();
  let res;
  let label;

  if (pick < 0.60) {
    if (Math.random() < 0.5) {
      res = http.get(`${BASE_URL}/users?limit=50`);
      label = 'list-users';
    } else {
      res = http.get(`${BASE_URL}/offers/user/${TEST_USER_ID}?limit=50`);
      label = 'offers-by-user';
    }
  } else if (pick < 0.90) {
    if (Math.random() < 0.5) {
      res = http.get(`${BASE_URL}/auth/me`, { headers: AUTH_HEADERS });
      label = 'auth-me';
    } else {
      res = http.get(`${BASE_URL}/orders/me`, { headers: AUTH_HEADERS });
      label = 'orders-me';
    }
  } else {
    // Normal write (no deep correctness check during high load to avoid RPS skew)
    const payload = {
      title: `Load Test Offer ${Math.random().toString(36).substring(7)}`,
      description: "Auto-generated by k6 high load test",
      price: Math.floor(Math.random() * 10000),
      currency: "USD",
      offerType: "PRODUCT",
      images: []
    };
    res = http.post(`${BASE_URL}/offers`, JSON.stringify(payload), { headers: AUTH_HEADERS });
    label = 'create-offer';
  }

  const expectedStatus = label === 'create-offer' ? 201 : 200;
  checkResponse(res, label, expectedStatus);
  sleep(0.5);
}
